def main():
    ok = miss = multi = 0
    plan = []
    for fn, old, new, note in EDITS:
        if new is None:
            continue
        p = os.path.join(BASE, fn)
        if not os.path.exists(p):
            print(f"[缺文件] {fn}")
            miss += 1
            continue
        t = open(p, encoding='utf-8').read()
        c = t.count(old)
        if c == 0:
            print(f"[未命中] {fn} :: {old[:34]}")
            miss += 1
        elif c > 1:
            print(f"[多处×{c}] {fn} :: {old[:34]}")
            multi += 1
        else:
            ok += 1
            plan.append((p, old, new, note))
    print(f"\n校验：可改 {ok} / 未命中 {miss} / 多处 {multi}")
    if not APPLY:
        print("（dry-run，未写盘。加 --apply 落盘）")
        for p, old, new, note in plan:
            print(f"  [{note}] {os.path.basename(p)}\n      {old[:50]}\n   →  {new[:50]}")
        return
    for p, old, new, note in plan:
        t = open(p, encoding='utf-8').read()
        open(p, 'w', encoding='utf-8').write(t.replace(old, new, 1))
    print(f"已落盘 {len(plan)} 处")

if __name__ == '__main__':
    main()
