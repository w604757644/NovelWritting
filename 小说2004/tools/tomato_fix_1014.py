def replace_dash_general(text):
    """其余破折号按三规则替换"""
    out = []
    i = 0
    n = len(text)
    stats = {'period_eol': 0, 'period_quote': 0, 'comma': 0}
    while i < n:
        if text[i:i+2] == '——':
            prev = text[i-1] if i > 0 else ''
            nxt = text[i+2:i+3]
            if nxt == '\n' or nxt == '':
                out.append('。'); stats['period_eol'] += 1
            elif prev in '”】':
                out.append('。'); stats['period_quote'] += 1
            else:
                out.append('，'); stats['comma'] += 1
            i += 2
        else:
            out.append(text[i]); i += 1
    return ''.join(out), stats

def main():
    total_manual = 0
    for f in sorted(glob.glob('正文_重写版/*.md')):
        base = os.path.basename(f)
        raw = open(f, encoding='utf-8').read()
        before_dash = raw.count('——')
        # 1) 手工修复
        fixes = MANUAL.get(base, [])
        for old, new in fixes:
            c = raw.count(old)
            if c != 1:
                print(f'[FAIL] {base}: 「{old[:20]}…」出现 {c} 次（应为1）'); sys.exit(1)
            raw = raw.replace(old, new)
            total_manual += 1
        # 2) 批量规则
        raw, stats = replace_dash_general(raw)
        after_dash = raw.count('——')
        # 3) 残留与伪影检查
        for bad in ['，，', '。。', '，。', '：，']:
            if bad in raw:
                for ln in raw.split('\n'):
                    if bad in ln:
                        print(f'[WARN] {base}: 伪影「{bad}」→ {ln[:60]}')
        open(f, 'w', encoding='utf-8').write(raw)
        print(f'{base}: 破折号 {before_dash}→{after_dash}  (句尾。{stats["period_eol"]} 引后。{stats["period_quote"]} 句中，{stats["comma"]})')
    print(f'\n手工修复 {total_manual} 处，全部成功')

if __name__ == '__main__':
    main()
